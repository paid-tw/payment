/**
 * Map a NewebPay Status code onto a stable {@link PaymentErrorCode}. Anything
 * unmapped falls through to PROVIDER (gateway-side failures, rate-limit locks,
 * bank declines) — the raw code is always preserved on the PaymentError.
 */
export function mapNewebpayErrorCode(raw: string): PaymentErrorCode {
  if (AUTH_CODES.has(raw)) return "AUTH";
  if (NOT_FOUND_CODES.has(raw)) return "NOT_FOUND";
  if (CONFLICT_CODES.has(raw)) return "CONFLICT";
  if (VALIDATION_CODES.has(raw)) return "VALIDATION";
  if (VALIDATION_PREFIXES.some((p) => raw.startsWith(p))) return "VALIDATION";
  return "PROVIDER";
}

/** The gateway message for a code, falling back to the raw response message. */
export function newebpayErrorMessage(raw: string, fallback?: string): string {
  return NEWEBPAY_ERROR_MESSAGES[raw] ?? fallback ?? "未知錯誤";
}
